-- 「13:30」の出勤枠
--
-- 清掃員が 13:30〜18:00 しか出られない日がある。その日は
--   ・16:00 のチェックインに間に合わせる清掃を 1件
--   ・その日に入室が無い部屋（翌日清掃）は 18:00 完了でよいので もう1件
-- がこなせる。合計2件だが、**チェックインのある部屋は1件まで**。
--
-- capacity の数字だけでは「2件」としか言えず、2件ともチェックインありの日に
-- 割り当てられてしまうため、上限を別の列で持つ。
--
--   NULL … 上限なし（0〜5 の数字のボタン。既存データはすべてこれ）
--   1    … チェックインのある部屋は1件まで（「13:30」のボタン）
--
-- 数字に番兵値を混ぜる（例: 6 を特別扱い）ことはしない。半年後に読んで
-- 意味が分かる形にしておく。将来ほかの時間帯を足すのもこの列で足りる。
ALTER TABLE availability ADD COLUMN checkin_limit INTEGER;
